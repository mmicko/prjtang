#!/usr/bin/env python3
"""
Check fuse expressions of database against reasons TD gives for each fuse.

Log file is created in TD with:
    bitgen -bit design.bit -info -attr_info -log_file design.log

For each fuse that is set TD writes what made it set (arc, property, value of
memory). Every such reason has to be a term of expression of that fuse in
database, and expression has to be true when only these terms are true.
"""

import argparse, sys, os, re, json
from collections import Counter, defaultdict

def evaluate(rpn, values, problems):
	stack = []
	for tok in rpn:
		if tok == "+":
			b = stack.pop(); a = stack.pop(); stack.append(a or b)
		elif tok == "*":
			b = stack.pop(); a = stack.pop(); stack.append(a and b)
		elif tok == "~":
			stack.append(not stack.pop())
		elif tok in ("FALSE", "TRUE"):
			stack.append(tok == "TRUE")
		elif tok == "(":
			problems["expression with '(' in rpn"] += 1
		else:
			stack.append(values[tok])
	if len(stack) != 1:
		return None
	return stack[0]

def match_token(tok, term):
	"""Return True when reason written by TD is this term of expression"""
	m = re.match(r"(\w+)\((.*)\)$", term)
	if not m:
		return False
	op, args = m.group(1), m.group(2).split(",")
	if op == "ARCVAL":
		return tok == args[0] + "." + args[1]
	if op == "PROPERTY":
		return tok == args[0].split(".", 1)[1] + ":" + args[1]
	if op == "WIRE":
		return tok == args[0]
	if op == "COMP":
		return tok == args[0]
	if op == "PORTS":
		return tok == args[0] + "." + args[1] or tok == args[0].split(".", 1)[1] + "." + args[1]
	if op in ("MEMORY", "SELECTOR"):
		# NAME=1010... (most significant bit first)
		mm = re.match(r"([\w.\[\]]+)=([01]+)$", tok)
		if not mm or mm.group(1) != args[1]:
			return False
		bits = mm.group(2)
		idx = int(args[2])
		return idx < len(bits) and bits[len(bits) - 1 - idx] == "1"
	return False

def main(argv):
	parser = argparse.ArgumentParser(prog="check_fuse_expressions",
		usage="%(prog)s [options] <design>.log <db_dir>")
	parser.add_argument("log_file", help="log file generated by TD bitgen -info -attr_info")
	parser.add_argument("db_dir", help="database directory of device (e.g. database/eg4/eagle_s20)")
	parser.add_argument("-n", type=int, default=3, help="examples to show for each kind of problem")
	args = parser.parse_args(argv[1:])

	with open(os.path.join(args.db_dir, "tilegrid.json")) as f:
		tilegrid = json.load(f)
	bits = dict()
	def get_bits(tile_type):
		if tile_type not in bits:
			d = defaultdict(list)
			fn = os.path.join(args.db_dir, "bits", tile_type + ".json")
			if os.path.exists(fn):
				with open(fn) as f:
					for e in json.load(f):
						d[e["name"]].append(e)
			bits[tile_type] = d
		return bits[tile_type]

	stats = Counter()
	problems = Counter()
	examples = defaultdict(list)
	ops = Counter()
	def problem(kind, text):
		problems[kind] += 1
		if len(examples[kind]) < args.n:
			examples[kind].append(text)

	inst = None
	with open(args.log_file) as f:
		for line in f:
			line = line.rstrip("\n")
			if line.startswith("//"):
				inst = line.split(":")[1].split(",")[0]
				continue
			if not line or line.startswith("#") or inst not in tilegrid:
				continue
			name, _, reason = line.partition("\t")
			tt = tilegrid[inst]["type"]
			entries = get_bits(tt).get(name)
			if not entries:
				problem("fuse not in database", "{}/{}".format(inst, name))
				continue
			stats["fuses"] += 1
			toks = reason.strip().strip("{}").split()
			# LUT0=<equation> <table> is written as two words
			merged = []
			for t in toks:
				if merged and re.match(r"^[01]+$", t) and "=" in merged[-1] and not re.match(r".*=[01]+$", merged[-1]):
					merged[-1] = merged[-1].split("=")[0] + "=" + t
				else:
					merged.append(t)
			toks = merged
			if not toks:
				stats["without reason"] += 1
			best = None
			for e in entries:
				true_terms = set()
				unmatched = []
				for t in toks:
					found = [k for k, v in e["data"].items() if match_token(t, v)]
					if found:
						true_terms.update(found)
					else:
						unmatched.append(t)
				values = {k: (k in true_terms) for k in e["data"]}
				for k, v in e["data"].items():
					if v in ("TRUE", "FALSE"):
						values[k] = (v == "TRUE")
				res = evaluate(e["rpn"], values, Counter())
				cand = (len(unmatched), 0 if res else 1, e, unmatched, res, true_terms)
				if best is None or cand[:2] < best[:2]:
					best = cand
			if best is None:
				continue
			_, _, e, unmatched, res, true_terms = best
			ident = "{}/{} [{}] {} {} <= {}".format(inst, name, tt, "".join(e["expr"])[:50],
				json.dumps(e["data"])[:160], " ".join(toks)[:120])
			for k in true_terms:
				ops[e["data"][k].split("(")[0]] += 1
			if unmatched:
				problem("reason is not term of expression", ident)
			elif res is None:
				problem("expression can not be evaluated", ident)
			elif not res:
				problem("expression false with reasons given", ident)
			else:
				stats["explained"] += 1
				if "~" in e["rpn"]:
					stats["explained, with negation"] += 1
				if "*" in e["rpn"]:
					stats["explained, with and"] += 1

	for k in ("fuses", "explained", "explained, with and", "explained, with negation", "without reason"):
		print("{:28} {}".format(k + ":", stats[k]))
	print("terms used: " + ", ".join("{} {}".format(k, v) for k, v in ops.most_common()))
	for k, v in problems.most_common():
		print("PROBLEM {}: {}".format(k, v))
		for x in examples[k]:
			print("    " + x)
	return 1 if problems else 0

if __name__ == '__main__':
	sys.exit(main(sys.argv))
