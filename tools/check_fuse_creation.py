#!/usr/bin/env python3
"""
Check that fuses reported by TD bitgen are found at locations predicted
by database in bitstream, and that no other bits are set.

Bitstream and log file are created in TD with:
    bitgen -bit design.bit -info -log_file design.log
"""

import argparse, sys, os, re, json
from collections import Counter, defaultdict

def read_blocks(bit_file):
	"""Return content of all blocks of .bit file"""
	with open(bit_file, "rb") as f:
		data = f.read()
	# text header finish with empty line
	pos = data.index(b"\n\n") + 2
	blocks = []
	while pos + 2 <= len(data):
		size = (int.from_bytes(data[pos:pos + 2], "big") + 7) // 8
		blocks.append(data[pos + 2:pos + 2 + size])
		pos += 2 + size
	return blocks

def read_bitstream(bit_file):
	"""Return set of (frame, bit) set in configuration memory, and PLL data"""
	blocks = read_blocks(bit_file)
	cram = set()
	pll = dict()
	frame_bytes = None
	idx = 0
	while idx < len(blocks):
		blk = blocks[idx]
		if blk[0] == 0xc7:
			# FRAMES command, number of frames and bytes per frame
			frame_bytes = int.from_bytes(blk[6:8], "big")
		elif blk[0] == 0xec:
			# FUSE_DATA command, followed by one block for each frame
			frames = int.from_bytes(blk[2:4], "big")
			for frame in range(frames):
				idx += 1
				for i, val in enumerate(blocks[idx][:frame_bytes]):
					if val:
						for j in range(8):
							if val & (0x80 >> j):
								cram.add((frame, i * 8 + j))
		elif blk[0] == 0xed and int.from_bytes(blk[1:3], "big") == 1:
			# MEMORY_DATA command with PLL configuration
			pll[blk[3]] = blk[4:-6]
		idx += 1
	return cram, pll

def main(argv):
	parser = argparse.ArgumentParser(prog="check_fuse_creation",
		usage="%(prog)s [options] <design>.bit <design>.log <db_dir>")
	parser.add_argument("bit_file", help="bitstream generated by TD bitgen")
	parser.add_argument("log_file", help="log file generated by TD bitgen")
	parser.add_argument("db_dir", help="database directory of device (e.g. database/eg4/eagle_s20)")
	parser.add_argument("--gap", type=int, action="append", default=None,
		help="position in database where 6 bits not used by database are inserted in frame (default for eg4: 974 and 2920)")
	parser.add_argument("-v", "--verbose", action="store_true", help="list all differences")
	args = parser.parse_args(argv[1:])
	gaps = args.gap if args.gap is not None else [974, 2920]

	with open(os.path.join(args.db_dir, "tilegrid.json")) as f:
		tilegrid = json.load(f)
	by_loc = dict()
	pll_at = dict()
	for t in tilegrid.values():
		by_loc[(t["x"], t["y"], t["type"].lower())] = t
		m = re.match(r"^pll(\d+)$", t["type"])
		if m:
			pll_at[(t["x"], t["y"])] = int(m.group(1))

	bits_cache = dict()
	def get_bits(tile_type):
		if tile_type not in bits_cache:
			d = defaultdict(list)
			with open(os.path.join(args.db_dir, "bits", tile_type + ".json")) as f:
				for e in json.load(f):
					d[e["name"]].append(e)
			bits_cache[tile_type] = d
		return bits_cache[tile_type]

	cram, pll_data = read_bitstream(args.bit_file)
	# PLL configuration is not part of configuration memory, it is kept in
	# 9 bit words (as block RAM data): bit of fuse is counted from end of word
	pll_set = set()
	for num, data in pll_data.items():
		for i in range(32 * 9):
			if data[i // 8] & (0x80 >> (i % 8)):
				pll_set.add((num, i // 9, 8 - i % 9))

	predicted = dict()
	pll_predicted = dict()
	stats = Counter()
	problems = []
	inst = None
	with open(args.log_file, "rt") as fin:
		for line in fin:
			line = line.strip()
			if line.startswith("//"):
				# // Inst:config_x0y68, type=config, wl_beg=0, bl_beg=0
				fields = dict(f.strip().split("=") for f in line[2:].split(",")[1:])
				inst = line.split(":")[1].split(",")[0]
				t = tilegrid.get(inst)
				if t is None:
					problems.append("instance {} not in tilegrid".format(inst))
					inst = None
					continue
				if t["type"] != fields["type"]:
					problems.append("instance {} type {} != {}".format(inst, t["type"], fields["type"]))
				if t["start_frame"] != int(fields["wl_beg"]) or t["start_bit"] != int(fields["bl_beg"]):
					problems.append("instance {} origin {},{} != {},{}".format(inst,
						t["start_frame"], t["start_bit"], fields["wl_beg"], fields["bl_beg"]))
				stats["instances"] += 1
			elif line.startswith("###") or line == "":
				continue
			elif inst is not None:
				stats["fuses"] += 1
				t = tilegrid[inst]
				entries = get_bits(t["type"]).get(line)
				ident = "{}/{}".format(inst, line)
				if entries is None:
					problems.append("{}: fuse not in database for type {}".format(ident, t["type"]))
					continue
				candidates = []
				for e in entries:
					if e["pll_info"]:
						if (t["x"], t["y"]) not in pll_at:
							problems.append("{}: no PLL at x{}y{}".format(ident, t["x"], t["y"]))
							continue
						pll_predicted.setdefault((pll_at[(t["x"], t["y"])], e["frame"], e["bit"]), []).append(ident)
						continue
					target = t
					if e["type"] != "NONE":
						key = (t["x"] + e["xoff"], t["y"] + e["yoff"], e["type"].lower())
						if key not in by_loc:
							problems.append("{}: no tile {} at x{}y{}".format(ident, key[2], key[0], key[1]))
							continue
						target = by_loc[key]
					frame = target["start_frame"] + e["frame"]
					col = target["start_bit"] + e["bit"]
					pos = col
					for g in gaps:
						if col >= g:
							pos += 6
					candidates.append((frame, pos))
				if len(candidates) == 1:
					predicted.setdefault(candidates[0], []).append(ident)
				elif len(candidates) > 1:
					# Same fuse name is used for more than one bit of this tile
					# type (e.g. one for each site), log does not tell which of
					# them was set, so accept any of them
					stats["ambiguous"] += 1
					found = [c for c in candidates if c in cram]
					if len(found) == 0:
						problems.append("{}: none of {} possible bits is set".format(ident, len(candidates)))
					for c in found:
						predicted.setdefault(c, []).append(ident)

	missing = sorted(k for k in predicted if k not in cram)
	unexplained = sorted(k for k in cram if k not in predicted)
	pll_missing = sorted(k for k in pll_predicted if k not in pll_set)
	pll_unexplained = sorted(k for k in pll_set if k not in pll_predicted)

	print("instances in log:          {}".format(stats["instances"]))
	print("fuses in log:              {}".format(stats["fuses"]))
	print("  with ambiguous name:     {}".format(stats["ambiguous"]))
	print("configuration memory bits: {}".format(len(cram)))
	print("  predicted and set:       {}".format(len(predicted) - len(missing)))
	print("  predicted but not set:   {}".format(len(missing)))
	print("  set but not predicted:   {}".format(len(unexplained)))
	print("PLL configuration bits:    {}".format(len(pll_set)))
	print("  predicted and set:       {}".format(len(pll_predicted) - len(pll_missing)))
	print("  predicted but not set:   {}".format(len(pll_missing)))
	print("  set but not predicted:   {}".format(len(pll_unexplained)))
	print("other problems:            {}".format(len(problems)))
	limit = None if args.verbose else 10
	for p in problems[:limit]:
		print("  " + p)
	for k in missing[:limit]:
		print("  not set: frame {} bit {} {}".format(k[0], k[1], predicted[k][:3]))
	for k in unexplained[:limit]:
		print("  not predicted: frame {} bit {}".format(k[0], k[1]))
	for k in pll_missing[:limit]:
		print("  not set: PLL {} word {} bit {} {}".format(k[0], k[1], k[2], pll_predicted[k][:3]))
	for k in pll_unexplained[:limit]:
		print("  not predicted: PLL {} word {} bit {}".format(k[0], k[1], k[2]))
	failed = len(missing) + len(unexplained) + len(pll_missing) + len(pll_unexplained) + len(problems)
	return 1 if failed else 0

if __name__ == '__main__':
	sys.exit(main(sys.argv))
